"""Generate code from the design sheets (the sheets are the source of truth).

  plugin/Generated/Sheets.g.cs   one C# class per sheet, one static instance per row (built from that row's columns)
  extractor/manifest.json        what the extractor reads from the player's Deadlock install
  extractor/manifest_owners.json which hero uses each manifest entry (package.py cuts a release down to its heroes)

Run tools/preflight.py first; gen refuses to run on a sheet with problems.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'design')

if '--no-preflight' not in sys.argv:
    r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'preflight.py')], capture_output=True, text=True)
    print(r.stdout.strip())
    # only "no implementing state" lines may remain while the states are being written
    others = [l for l in r.stdout.splitlines() if l.startswith('  -') and 'no implementing state' not in l]
    if others:
        sys.exit('gen: fix the preflight problems first')
    # a preflight that crashed prints neither problems nor the clean line: never generate from it
    if 'PREFLIGHT' not in r.stdout:
        sys.exit('gen: preflight did not finish: ' + r.stderr.strip())

def load(n):
    return json.load(open(os.path.join(D, n + '.json'), encoding='utf-8'))

def pascal(s):
    return ''.join(p[:1].upper() + p[1:] for p in s.replace('-', '_').split('_'))

def cs_value(v):
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return f'{v}f' if False else str(v)
    if isinstance(v, float): return repr(v) + 'f'
    if isinstance(v, list): return 'new string[] { ' + ', '.join(cs_value(x) for x in v) + ' }'
    return '"' + str(v).replace('\\', '\\\\').replace('"', '\\"') + '"'

def cs_type(vals):
    if all(isinstance(v, bool) for v in vals): return 'bool'
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals): return 'float'
    if all(isinstance(v, list) for v in vals): return 'string[]'
    return 'string'

def emit_sheet(name, cls):
    s = load(name)
    out = [f'    /// <summary>Row of design/{name}.json. {s["about"][:160].replace("<", "").replace(">", "")}...</summary>',
           f'    public sealed class {cls}', '    {']
    types = {}
    for c in s['columns']:
        t = cs_type([r[c] for r in s['rows']])
        types[c] = t
        out.append(f'        public {t} {pascal(c)};')
    out.append('')
    out.append(f'        public static readonly {cls}[] All = new {cls}[]')
    out.append('        {')
    for r in s['rows']:
        fields = []
        for c in s['columns']:
            v = r[c]
            if types[c] == 'float': v = float(v)
            fields.append(f'{pascal(c)} = {cs_value(v)}')
        out.append(f'            new {cls} {{ ' + ', '.join(fields) + ' },')
    out.append('        };')
    out.append('    }')
    return '\n'.join(out)

parts = ['// <auto-generated> by tools/gen.py from design/*.json. Do not edit; change the sheet and regenerate. </auto-generated>',
         'namespace DeadlockOfRain.Sheets', '{']
for name, cls in [('heroes', 'HeroRow'), ('stats', 'StatRow'), ('skills', 'SkillRow'), ('equipment', 'EquipmentRow'), ('buffs', 'BuffRow'),
                  ('animations', 'AnimRow'), ('sounds', 'SoundRow'), ('effects', 'EffectRow'), ('hooks', 'HookRow'), ('voice', 'VoiceRow')]:
    parts.append(emit_sheet(name, cls))
    parts.append('')
h = load('heroes')
parts.append('    public static class SheetInfo')
parts.append('    {')
parts.append(f'        public const string AnchorHero = "{h["anchorHero"]}";')
parts.append(f'        public const string AnchorRoR2Body = "{h["anchorRoR2Body"]}";')
parts.append('    }')
parts.append('}')
os.makedirs(os.path.join(ROOT, 'plugin', 'Generated'), exist_ok=True)
open(os.path.join(ROOT, 'plugin', 'Generated', 'Sheets.g.cs'), 'w', encoding='utf-8').write('\n'.join(parts) + '\n')

# extractor manifest
ANIM_RIG_COLUMNS = {'hero', 'upperBodyBone', 'gunArms', 'gunBone', 'gunHand', 'muzzle', 'muzzleLeft', 'muzzleForward', 'clothParents', 'ragdollBones', 'ragdollThickness', 'rigPrefix', 'loopSecondary', 'springRoots', 'springStiffness', 'springDamping', 'springGravity', 'propBones', 'steadyClips'}  # animations columns that are not clip names
anims = {r['hero']: r for r in load('animations')['rows']}
skills = load('skills')['rows']
buffs = load('buffs')['rows']
sounds = load('sounds')['rows']
manifest = {'heroes': [], 'images': [], 'soundEvents': []}
for hero in h['rows']:
    a = anims[hero['id']]
    clips = sorted({a[c] for c in load('animations')['columns'] if c not in ANIM_RIG_COLUMNS and a[c] != 'none'})
    # split: meshes kept as their own part (Rat King's ammo belt; extractor 1.6.0+)
    manifest['heroes'].append({'id': hero['id'], 'key': hero['deadlockKey'], 'vmdl': hero['vmdl'], 'meshes': hero['meshInclude'], 'clips': clips,
                               'split': [m for m in hero['splitMeshes'] if m != 'none']})
    manifest['images'] += [hero['imageSmall'], hero['imageCard']]
    if hero['passiveIcon'] != 'none': manifest['images'].append(hero['passiveIcon'])
manifest['images'] += [s['icon'] for s in skills] + [b['icon'] for b in buffs if b['icon'] != 'none']
manifest['images'] = sorted(set(manifest['images']))
manifest['soundEvents'] = sorted({r[c] for r in sounds for c in ['cast', 'loop', 'hit', 'end', 'reload', 'castLayer', 'hitLayer', 'tick', 'tickFinal'] if r[c] != 'none'})
manifest['soundEventFiles'] = sorted({hero['soundevents'] for hero in h['rows']})
# voice lines: every numbered take of each group, sounds/vo/<group>_NN.vsnd (design/voice.json)
manifest['voiceGroups'] = sorted({r['group'] for r in load('voice')['rows']})
# groups read whole (a chained row or one that skips takes: Rat King's named rats); the others keep the first 24 takes
manifest['voiceAllTakes'] = sorted({r['group'] for r in load('voice')['rows'] if r['chain'] > 0 or r['skipTakes'] != 'none'})
# Deadlock models used as plain meshes by our effects (effects kind prop: the Cube, Goo Ball's sphere, the fist; extractor 1.5.0+)
effects = load('effects')['rows']
# extractor 1.6.0+: a prop's meshes (none = all) and the clips read with its skeleton (Rat King's rat, his banner's sewer)
manifest['props'] = [{'id': e['id'], 'vmdl': e['addressable'], 'meshes': [m for m in e['meshes'] if m != 'none'], 'clips': [c for c in e['clips'] if c != 'none']}
                     for e in effects if e['kind'] == 'prop']
json.dump(manifest, open(os.path.join(ROOT, 'extractor', 'manifest.json'), 'w', encoding='utf-8'), indent=2)
# which hero(es) use each image, sound event and voice group, so tools/package.py can cut the manifest down to a
# release's heroes (thunderstore/release.json); an entry with no owner (shared buff icons) is always kept
skill_hero = {s['id']: s['hero'] for s in skills}
owners = {}
def own(entry, hero):
    owners.setdefault(entry, set()).add(hero)
for hero in h['rows']:
    for c in ['imageSmall', 'imageCard', 'passiveIcon', 'soundevents']:
        if hero[c] != 'none': own(hero[c], hero['id'])
for s in skills: own(s['icon'], s['hero'])
for r in sounds:
    for c in ['cast', 'loop', 'hit', 'end', 'reload', 'castLayer', 'hitLayer', 'tick', 'tickFinal']:
        base = r['skill'].split('/')[0]   # 'mokrill_gun/step': a variant of the gun row
        if r[c] != 'none' and base in skill_hero: own(r[c], skill_hero[base])
for r in load('voice')['rows']: own(r['group'], r['hero'])
# a prop belongs to the hero its id starts with (viscous_cube_prop)
for e in effects:
    if e['kind'] == 'prop':
        for hero in h['rows']:
            if e['id'].startswith(hero['id'] + '_'): own(e['id'], hero['id'])
json.dump({k: sorted(v) for k, v in sorted(owners.items())}, open(os.path.join(ROOT, 'extractor', 'manifest_owners.json'), 'w', encoding='utf-8'), indent=2)
print(f'gen: wrote plugin/Generated/Sheets.g.cs and extractor/manifest.json ({len(manifest["images"])} images, {len(manifest["soundEvents"])} sound events, {len(manifest["voiceGroups"])} voice groups, {len(manifest["props"])} props)')
